using Okf.Core;

namespace Okf.Cli.Tests.Generated;

/// <summary>
/// End-to-end <c>okf generated stamp</c> (AD-52): what it writes, what it leaves alone,
/// what it warns about, and the exit-code contract (CLI-14).
/// </summary>
public class GeneratedCommandTests
{
    [Fact]
    public void HelpExitsZeroAndSaysTheStampReopensTheInbox()
    {
        using var tree = new TempTree();
        var run = CliHarness.RunIn(tree.Root, tree.Root, "generated", "--help");

        Assert.Equal(CliApplication.ExitSuccess, run.ExitCode);
        Assert.Contains("okf generated stamp <concept-path>...", run.Output, StringComparison.Ordinal);
        Assert.Contains("UNACKNOWLEDGED again", run.Output, StringComparison.Ordinal);
    }

    [Fact]
    public void TheCommandIsReachableFromTheTopLevelUsage()
    {
        using var tree = new TempTree();
        Assert.Contains("okf generated stamp <concept>...", CliHarness.RunIn(tree.Root, tree.Root, "help").Output, StringComparison.Ordinal);
    }

    [Fact]
    public void TheStampReplacesTheExistingOneAndMovesNoOtherLine()
    {
        using var tree = new Bundle();
        var before = tree.Read("widgets.md");

        var run = tree.Stamp("widgets.md", "claude-fable/5", "2026-08-16T14:00:00Z");

        Assert.Equal(CliApplication.ExitSuccess, run.ExitCode);
        Assert.Contains("generated by claude-fable/5 at 2026-08-16T14:00:00Z", run.Output, StringComparison.Ordinal);
        Assert.Contains("Stamped 1 concept as generated by claude-fable/5.", run.Output, StringComparison.Ordinal);

        var after = tree.Read("widgets.md");
        Assert.Equal(
            ["generated: { by: \"claude-fable/5\", at: 2026-08-16T14:00:00Z }"],
            after.Split('\n').Except(before.Split('\n'), StringComparer.Ordinal));
        Assert.Equal(
            ["generated: { by: claude-opus/4, at: 2020-01-01T00:00:00Z }"],
            before.Split('\n').Except(after.Split('\n'), StringComparer.Ordinal));
    }

    [Fact]
    public void AConceptWithNoStampGainsOne()
    {
        using var tree = new Bundle();

        var run = tree.Stamp("plain.md", "process:nightly-refresh", "2026-08-16T14:00:00Z");

        Assert.Equal(CliApplication.ExitSuccess, run.ExitCode);
        Assert.Contains(
            "generated: { by: \"process:nightly-refresh\", at: 2026-08-16T14:00:00Z }",
            tree.Read("plain.md"),
            StringComparison.Ordinal);
    }

    [Fact]
    public void TheFreshStampPutsTheConceptBackOnTheInbox()
    {
        // AD-21 through the CLI: acknowledgment is derived, so a `generated.at` newer than
        // the latest verification makes the concept unacknowledged again. The help text
        // says so; this is the behaviour behind the sentence.
        using var tree = new Bundle();
        var cleared = tree.Run("inbox", tree.Path("."), "--fail-if-any");

        tree.Stamp("verified.md", "claude-fable/5", "2026-08-16T14:00:00Z");
        var after = tree.Run("inbox", tree.Path("."), "--fail-if-any");

        Assert.DoesNotContain("verified.md", cleared.Output, StringComparison.Ordinal);
        Assert.Equal(CliApplication.ExitDiagnostics, after.ExitCode);
        Assert.Contains("verified.md", after.Output, StringComparison.Ordinal);
    }

    [Fact]
    public void AHumanActorIsAllowedAndWarnedAbout()
    {
        using var tree = new Bundle();

        var run = tree.Stamp("widgets.md", "human:ringo", "2026-08-16T14:00:00Z");

        Assert.Equal(CliApplication.ExitSuccess, run.ExitCode);
        Assert.Contains("okf: warning:", run.Error, StringComparison.Ordinal);
        Assert.Contains("the human surface is `okf verify`", run.Error, StringComparison.Ordinal);
        Assert.Contains("\"human:ringo\"", tree.Read("widgets.md"), StringComparison.Ordinal);
    }

    [Fact]
    public void DryRunReportsTheStampAndWritesNothing()
    {
        using var tree = new Bundle();
        var before = tree.Read("widgets.md");

        var run = tree.Run(
            "generated", "stamp", tree.Path("widgets.md"), "--by", "claude-fable/5", "--at", "2026-08-16T14:00:00Z", "--dry-run");

        Assert.Equal(CliApplication.ExitSuccess, run.ExitCode);
        Assert.Contains(
            "would write generated: { by: \"claude-fable/5\", at: 2026-08-16T14:00:00Z }",
            run.Output,
            StringComparison.Ordinal);
        Assert.Equal(before, tree.Read("widgets.md"));
    }

    [Fact]
    public void StampingSeveralConceptsInOneRunGivesThemAllTheSameInstant()
    {
        using var tree = new Bundle();

        var run = tree.Run(
            "generated", "stamp", tree.Path("widgets.md"), tree.Path("plain.md"), "--by", "claude-fable/5");

        Assert.Equal(CliApplication.ExitSuccess, run.ExitCode);
        Assert.Contains("Stamped 2 concepts as generated by claude-fable/5.", run.Output, StringComparison.Ordinal);
        Assert.Equal(Stamp(tree.Read("widgets.md")), Stamp(tree.Read("plain.md")));
    }

    [Fact]
    public void ARunThatRefusesOneConceptStampsNoneOfThem()
    {
        using var tree = new Bundle();
        var before = tree.Read("widgets.md");

        var run = tree.Run(
            "generated", "stamp", tree.Path("widgets.md"), tree.Path("nope.md"), "--by", "claude-fable/5");

        Assert.Equal(CliApplication.ExitUsage, run.ExitCode);
        Assert.Contains("no such concept", run.Error, StringComparison.Ordinal);
        Assert.Equal(before, tree.Read("widgets.md"));
    }

    [Fact]
    public void AFileWithNoFrontmatterIsRefusedRatherThanGivenSome()
    {
        using var tree = new Bundle();
        var readme = tree.Write("README.md", "# Just a readme\n\nNo frontmatter here.\n");
        var before = File.ReadAllText(readme);

        var run = tree.Run("generated", "stamp", readme, "--by", "claude-fable/5");

        Assert.Equal(CliApplication.ExitUsage, run.ExitCode);
        Assert.Contains("has no frontmatter", run.Error, StringComparison.Ordinal);
        Assert.Equal(before, File.ReadAllText(readme));
    }

    [Fact]
    public void AnUnparseableConceptIsRefusedWithAPointerToLint()
    {
        using var tree = new Bundle();
        var broken = tree.Write("broken.md", "---\nkey: [unterminated\n---\n\nBody.\n");
        var before = File.ReadAllText(broken);

        var run = tree.Run("generated", "stamp", broken, "--by", "claude-fable/5");

        Assert.Equal(CliApplication.ExitUsage, run.ExitCode);
        Assert.Contains("okf lint", run.Error, StringComparison.Ordinal);
        Assert.Equal(before, File.ReadAllText(broken));
    }

    [Theory]
    [InlineData("ringo")]
    [InlineData("human:")]
    [InlineData("""claude/5", at: 2020-01-01 }""")]
    public void AByThatIsNotASpecActorIsRefused(string actor)
    {
        using var tree = new Bundle();
        var before = tree.Read("widgets.md");

        var run = tree.Run("generated", "stamp", tree.Path("widgets.md"), "--by", actor);

        Assert.Equal(CliApplication.ExitUsage, run.ExitCode);
        Assert.Contains("is not an actor", run.Error, StringComparison.Ordinal);
        Assert.Equal(before, tree.Read("widgets.md"));
    }

    [Fact]
    public void WithoutAByActorNothingIsWritten()
    {
        using var tree = new Bundle();
        var before = tree.Read("widgets.md");

        var run = tree.Run("generated", "stamp", tree.Path("widgets.md"));

        Assert.Equal(CliApplication.ExitUsage, run.ExitCode);
        Assert.Contains("no `--by` actor", run.Error, StringComparison.Ordinal);
        Assert.Equal(before, tree.Read("widgets.md"));
    }

    [Theory]
    [InlineData("2026-08-16T14:00:00-05:00")]
    [InlineData("now")]
    public void APinnedInstantThatIsNotTheCanonicalFormIsRefused(string instant)
    {
        using var tree = new Bundle();

        var run = tree.Run("generated", "stamp", tree.Path("widgets.md"), "--by", "claude-fable/5", "--at", instant);

        Assert.Equal(CliApplication.ExitUsage, run.ExitCode);
        Assert.Contains("is not a canonical instant", run.Error, StringComparison.Ordinal);
    }

    [Fact]
    public void ASubcommandIsRequiredAndOnlyStampExists()
    {
        using var tree = new Bundle();

        Assert.Equal(CliApplication.ExitUsage, tree.Run("generated").ExitCode);
        Assert.Contains("no subcommand", tree.Run("generated").Error, StringComparison.Ordinal);
        Assert.Contains(
            "unknown generated subcommand 'clear'",
            tree.Run("generated", "clear", tree.Path("widgets.md")).Error,
            StringComparison.Ordinal);
    }

    [Fact]
    public void NamingNoConceptIsAUsageFailure()
    {
        using var tree = new Bundle();
        var run = tree.Run("generated", "stamp", "--by", "claude-fable/5");

        Assert.Equal(CliApplication.ExitUsage, run.ExitCode);
        Assert.Contains("no concept named", run.Error, StringComparison.Ordinal);
    }

    /// <summary>The <c>at</c> of a concept's generation stamp.</summary>
    private static string? Stamp(string text) =>
        OkfDocument.Parse(text).Frontmatter.TryGetValue("generated", out var generated)
        && generated is OkfMapping mapping
        && mapping.TryGetValue("at", out var at)
        && at is OkfScalar scalar
            ? scalar.Value
            : null;

    /// <summary>A throwaway bundle holding three concepts and a home with no okf configuration.</summary>
    private sealed class Bundle : IDisposable
    {
        private readonly TempTree _tree = new();

        public Bundle()
        {
            _tree.CreateDirectory("bundle");
            Write(
                "widgets.md",
                "---\ntype: Concept\ntitle: Widgets\ngenerated: { by: claude-opus/4, at: 2020-01-01T00:00:00Z }\n---\n\nBody.\n");
            Write("plain.md", "---\ntype: Concept\ntitle: Plain\n---\n\nBody.\n");
            Write(
                "verified.md",
                "---\ntype: Concept\ntitle: Verified\ngenerated: { by: claude-opus/4, at: 2020-01-01T00:00:00Z }\n"
                + "verified:\n  - { by: \"human:ringo\", at: 2021-01-01T00:00:00Z }\n---\n\nBody.\n");
            Home = _tree.CreateDirectory("home");
        }

        /// <summary>A home directory with no okf configuration in it.</summary>
        public string Home { get; }

        public string Path(string relativePath) =>
            System.IO.Path.Combine(_tree.Root, "bundle", relativePath);

        public string Read(string relativePath) => File.ReadAllText(Path(relativePath));

        public string Write(string relativePath, string content) =>
            _tree.Write(System.IO.Path.Combine("bundle", relativePath), content);

        public CliRun Run(params string[] args) =>
            CliHarness.RunIn(System.IO.Path.Combine(_tree.Root, "bundle"), Home, args);

        public CliRun Stamp(string relativePath, string actor, string at) =>
            Run("generated", "stamp", Path(relativePath), "--by", actor, "--at", at);

        public void Dispose() => _tree.Dispose();
    }
}
